    def get_user_by_username(db: Session, username: str) -> User | None: # будем передавать сессию созданную в фикстуре и через нее работать в таблице и имя по которому бдет искать созданного пользовтеля
        return db.query(User).filter_by(username=username).first() # filter_by нужен для поиска данных по заданному условию. first() - возвращает первый объект который удовлетворяет условию
        # обращаемся к таблице юзер и фильтруем поле юзернейм по имени которое мы создали и нашли первую запись, вернули ее
